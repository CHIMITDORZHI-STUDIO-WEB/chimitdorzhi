<p>Условия обычно лежат в правилах страхования. Они обязывают вас, если на них есть ссылка в договоре и их приложили с отметкой о вручении (ст. 943). Вы обязаны сообщить страховщику известные вам существенные обстоятельства, а ложные сведения дают ему право добиваться признания договора недействительным (ст. 944).</p>

