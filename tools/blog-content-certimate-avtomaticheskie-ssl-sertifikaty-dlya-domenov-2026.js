<p>Работает он как рабочий процесс из блоков. Первый блок запрашивает сертификат, второй раскладывает его по местам назначения, третий проверяет, что на сайте стоит именно он, четвёртый отправляет уведомление. Всё это собирается мышкой в веб-интерфейсе, программировать не нужно.</p>

