<p>Права. Nmap ставится отдельно. Чтобы увидеть MAC-адреса и производителей, программу нужно запускать с правами администратора (sudo в Linux, запуск от имени администратора в Windows). Без них видны только IP и имена, а различить устройства сложнее.</p>

