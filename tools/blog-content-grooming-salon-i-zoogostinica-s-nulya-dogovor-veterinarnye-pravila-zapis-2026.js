<p>Закон о ветеринарии (4979-1, ред. от 29.12.2025), ст. 18: за здоровье и содержание животных отвечают владельцы, обязаны соблюдать ветправила. Ст. 1.1 требует регистрации у ветеринаров, ведущих предпринимательскую деятельность, это про лечение, не про стрижку. Лицензии на ветеринарную деятельность в тексте закона нет, а перечень лицензируемых видов по 99-ФЗ я не сверял. Какие прививки и документы требовать, определяют ветправила и региональная служба. Уточните в станции по борьбе с болезнями животных вашего региона.</p>

