<p>Сервер компании собирали два года назад. Сайт, CRM, пара ботов, мини-приложение. Перед ними стоит Nginx, и конфиг для него правили шесть раз: добавляли поддомены, копировали блоки, чинили редирект. Сертификаты выпускает отдельная программа по таймеру, и таймер однажды тихо перестал работать.</p>

