module.exports = {
  PAGES,
  apply(articles) {
    for (const art of articles) {
      const o = art && PAGES[art.slug];
      if (!o || !art.contentHtml) continue;
      if (o.metaTitle) art.metaTitle = o.metaTitle;
      if (o.metaDescription) art.metaDescription = o.metaDescription;
      art.dateModified = '2026-11-26';
      if (art.contentHtml.includes('id="skolko-u-menya"')) continue;
      const html = art.contentHtml;
      const t = html.indexOf('blog-tldr');
      const end = t < 0 ? -1 : html.indexOf('</div>', t);
      const cut = end < 0 ? 0 : end + 6;
      art.contentHtml = html.slice(0, cut) + o.leadHtml() + html.slice(cut);
    }
  },
};
