<p>Для проверки хватит одной машины с одним диском, но защиты от поломки диска там нет. Для настоящей защиты нужно несколько дисков в одном наборе, а лучше несколько узлов. Точную схему я подбираю под объём данных и бюджет, универсального минимума под любой проект не существует.</p>

