<p>Порт 9000 принимает S3-запросы, на 9001 живёт веб-консоль. Контейнер запускается от обычного пользователя с номером 10001 вместо root, поэтому каталоги надо подготовить заранее. Логин и пароль по умолчанию в документации указаны rustfsadmin, и их нужно сменить до того, как порты станут видны из интернета. Если сервера у вас ещё нет, начните с материала про <a href="/blog/svoy-vps-s-nulya-docker-nginx-https-2026/">свой VPS с Docker, nginx и HTTPS</a>: перед хранилищем нужен шифрованный вход.</p>

