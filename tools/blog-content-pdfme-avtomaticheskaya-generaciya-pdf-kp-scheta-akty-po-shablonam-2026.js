<p>Юридическая оговорка. Счёт, акт и договор требуют проверки реквизитов и обязательных полей бухгалтером или юристом. Библиотека рисует документ, правильность содержания за вами. Электронная подпись и ЭДО это отдельный вопрос со своими операторами и правилами, я здесь не утверждаю, как они устроены.</p>

