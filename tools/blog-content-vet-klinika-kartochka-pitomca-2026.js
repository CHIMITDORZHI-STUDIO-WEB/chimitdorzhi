<p>Второе ограничение: доверие к номеру. Много старых карточек с чужими или устаревшими телефонами. Первый прогон напоминаний по базе покажет, сколько номеров мёртвые: сообщения не доходят, и это видно в отчёте за один день. Их лучше вычищать на приёме, когда хозяин рядом и может подтвердить контакт.</p>

