<p>Пакеты малых моделей называются MinerU-4_models_onnx и MinerU-4_models_torch, плюс VLM MinerU2.5-Pro-2605-1.2B для standard. Источник задаёт параметр <code>model.source</code>: <code>huggingface</code>, <code>modelscope</code>, <code>local</code> или <code>auto</code>. Режим auto сначала пробует Hugging Face, а если тот недоступен, переходит на ModelScope. Те же пакеты зарегистрированы в обоих хранилищах.</p>

