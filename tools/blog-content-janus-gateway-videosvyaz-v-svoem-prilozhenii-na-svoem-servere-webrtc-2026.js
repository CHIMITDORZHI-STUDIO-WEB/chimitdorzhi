<p>TURN. В конфиге Janus сказано прямо: TURN для пользователей настраивается на стороне клиента, а в Janus его прописывают, только если сам сервер сидит за строгим фаерволом. Значит, отдельный TURN-сервер вам нужен для клиентов из жёстких сетей. В комментарии к конфигу упомянут coturn как совместимый с TURN REST API. Для сервера за NAT есть параметры nat_1_1_mapping и rtp_port_range. Что часть пользователей без TURN не подключится, это общее правило WebRTC.</p>

