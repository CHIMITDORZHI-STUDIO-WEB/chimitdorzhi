<p>Во-вторых, контроль сотрудников законен, когда он прозрачен. Это значит: сотрудник уведомлён о контроле, подписал согласие, а в компании действуют локальные акты — положение о коммерческой тайне и введённый режим коммерческой тайны. Когда правила игры объявлены заранее, контроль корпоративных систем — нормальная практика.</p>

