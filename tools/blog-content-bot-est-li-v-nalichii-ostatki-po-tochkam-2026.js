<p>Бронь снимается по таймеру, и это сделано сознательно. Без таймера отложенные товары копятся, продавцы забывают вернуть их на полку, и остаток для остальных покупателей занижается. Для магазина у дома обычно хватает часа, для точки в торговом центре можно поставить два.</p>

