<p>Точность бота равна актуальности остатков в учёте. Если приёмку заносят на следующий день, бот в понедельник утром покажет цифры воскресенья. Когда остатки в учёте разошлись с полками, начинать надо с учёта. Как навести там порядок без остановки магазина, я разбирал в статье <a href="/blog/uchet-ostatkov-bez-1c-2026/">про учёт остатков без 1С</a>.</p>

